def svg(name, cls="px-icon"):
    """Return an inline SVG for a pixel icon (crisp edges, scalable)."""
    main, accent = [], []
    for y, row in enumerate(ICONS[name]):
        for x, ch in enumerate(row):
            if ch == "#":
                main.append(f"M{x} {y}h1v1h-1z")
            elif ch == "o":
                accent.append(f"M{x} {y}h1v1h-1z")
    return (f'<svg class="{cls}" viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">'
            f'<path fill="currentColor" d="{"".join(main)}"/>'
            f'<path class="px-accent" d="{"".join(accent)}"/></svg>')


def background():
    """Decorative, animated arcade background (hidden from assistive tech)."""
    invader = svg("invader", "invader-sprite")
    return (
        '<div class="arcade-bg" aria-hidden="true">'
        '<div class="bg-glow"></div>'
        '<div class="bg-stars s1"></div><div class="bg-stars s2"></div><div class="bg-stars s3"></div>'
        '<div class="bg-floor"><div class="bg-grid"></div></div>'
        f'<span class="invader i1">{invader}</span><span class="invader i2">{invader}</span><span class="invader i3">{invader}</span>'
        '<div class="bg-scan"></div>'
        "</div>"
    )


def star_css():
    """Box-shadow star fields, generated deterministically at build time."""
    rng = random.Random(537)
    colors = ["#ffffff", "#8be9ff", "#ff9ae8", "#ffe27a"]
    rules = []
    for layer, (count, size) in enumerate([(70, 2), (40, 3), (18, 4)], 1):
        shadows = ", ".join(
            f"{rng.randint(0, 2000)}px {rng.randint(0, 1400)}px 0 {rng.choice(colors)}" for _ in range(count))
        rules.append(f".bg-stars.s{layer}{{width:{size}px;height:{size}px;box-shadow:{shadows}}}")
    return "\n".join(rules)
